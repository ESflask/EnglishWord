def filter_and_take(candidates, count):
    res = []
    seen = set()
    for eng, jap, cat in candidates:
        if eng.lower() not in existing_words and eng.lower() not in seen:
            res.append((eng, jap, cat))
            seen.add(eng.lower())
    return res

